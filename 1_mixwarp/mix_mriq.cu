__global__ void mix_kernel(
    half *a, half *b, float *c,
    int MATRIX_M, int MATRIX_N, int MATRIX_K,
    int wmma_grid_dim_x, int wmma_block_dim_x, 
    int wmma_iter,
    int numK, int kGlobalIndex, float* x, float* y, float* z, float* Qr , float* Qi,
    int mriq_grid_dim_x, int mriq_block_dim_x, 
    int mriq_iter){
    int thread_step = 0;
    if (threadIdx.x < wmma_block_dim_x) {
        mix_tzgemm0(a, b, c, 
            MATRIX_M, MATRIX_N, MATRIX_K,
            wmma_grid_dim_x, wmma_block_dim_x, wmma_iter);
    } else if (threadIdx.x < wmma_block_dim_x * 2) {
        thread_step = wmma_block_dim_x;
        mix_tzgemm1(a, b, c, 
            MATRIX_M, MATRIX_N, MATRIX_K,
            wmma_grid_dim_x, wmma_block_dim_x, wmma_iter, thread_step);
    } else {    
        thread_step = wmma_block_dim_x * 2;
        mix_mriq(numK, kGlobalIndex, x, y, z, Qr, Qi,
            mriq_grid_dim_x, mriq_block_dim_x, thread_step, mriq_iter);
    } 
}


